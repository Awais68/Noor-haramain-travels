// scripts/generate-blur.mjs
// ---------------------------------------------------------------------------
// Generates tiny base64 LQIP (low-quality image placeholder) data URLs for
// every Unsplash photo referenced in src/lib/site.ts, and writes them to
// src/lib/blur.generated.ts as a { [photoId]: dataURL } map.
//
// next/image reads these via `placeholder="blur"` + `blurDataURL`, giving a
// smooth blur-up while the full image streams in — no runtime cost, baked at
// build time. Re-run with `npm run images:blur` whenever you add a photo.
//
// It fetches a small JPEG from the Unsplash CDN, then uses sharp to downscale
// to 16px, strip all metadata/ICC profiles, and re-encode as WebP — yielding
// clean placeholders of only a few hundred bytes each. Needs network once.
// If a fetch fails, it falls back to a flat forest-green placeholder so the
// build never breaks.
// ---------------------------------------------------------------------------

import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import sharp from "sharp";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, "..");
const SITE = join(root, "src/lib/site.ts");
const OUT = join(root, "src/lib/blur.generated.ts");

// Flat forest-green fallback (matches bg-forest-800) — valid 4x3 JPEG.
const FALLBACK =
  "data:image/jpeg;base64,/9j/4AAQSkZJRgABAQAAAQABAAD/2wBDAAYEBQYFBAYGBQYHBwYIChAKCgkJChQODwwQFxQYGBcUFhYaHSUfGhsjHBYWICwgIyYnKSopGR8tMC0oMCUoKSj/2wBDAQcHBwoIChMKChMoGhYaKCgoKCgoKCgoKCgoKCgoKCgoKCgoKCgoKCgoKCgoKCgoKCgoKCgoKCgoKCgoKCgoKCj/wAARCAADAAQDASIAAhEBAxEB/8QAFQABAQAAAAAAAAAAAAAAAAAAAAf/xAAUEAEAAAAAAAAAAAAAAAAAAAAA/8QAFQEBAQAAAAAAAAAAAAAAAAAAAAX/xAAUEQEAAAAAAAAAAAAAAAAAAAAA/9oADAMBAAIRAxEAPwCVQAf/2Q==";

async function toDataURL(id) {
  const url = `https://images.unsplash.com/${id}?fit=crop&w=64&q=40&fm=jpg`;
  const res = await fetch(url, { headers: { Accept: "image/jpeg" } });
  if (!res.ok) throw new Error(`HTTP ${res.status}`);
  const input = Buffer.from(await res.arrayBuffer());
  // Downscale to 16px wide, drop metadata/ICC, re-encode as tiny WebP.
  const out = await sharp(input)
    .resize(16, null, { fit: "inside" })
    .webp({ quality: 45, effort: 6 })
    .toBuffer();
  return `data:image/webp;base64,${out.toString("base64")}`;
}

async function main() {
  const src = await readFile(SITE, "utf8");
  // Collect unique Unsplash ids ("photo-...") from the photos map.
  const ids = [...new Set([...src.matchAll(/id:\s*"(photo-[a-z0-9-]+)"/gi)].map((m) => m[1]))];
  if (ids.length === 0) {
    console.error("No photo ids found in src/lib/site.ts — nothing to do.");
    process.exit(1);
  }

  console.log(`Generating blur placeholders for ${ids.length} photos…`);
  const entries = {};
  for (const id of ids) {
    try {
      entries[id] = await toDataURL(id);
      process.stdout.write("·");
    } catch (err) {
      entries[id] = FALLBACK;
      console.warn(`\n  ! ${id}: ${err.message} — using fallback`);
    }
  }
  process.stdout.write("\n");

  const body =
    `// AUTO-GENERATED by scripts/generate-blur.mjs — do not edit by hand.\n` +
    `// Run \`npm run images:blur\` to regenerate after adding photos.\n` +
    `export const blurData: Record<string, string> = ${JSON.stringify(entries, null, 2)};\n`;

  await writeFile(OUT, body, "utf8");
  console.log(`Wrote ${ids.length} placeholders → src/lib/blur.generated.ts`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
